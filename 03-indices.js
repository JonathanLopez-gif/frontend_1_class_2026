let text = `JavaScript`

// Usando índices

let first1 = text[0]
let last1 = text[text.length - 1]

console.log(`First character: ${first1}`) 
console.log(`Last character: ${last1}`)

// Usando charAt()

let first2 = text.charAt(0)
let last2 = text.charAt(text.length - 1)

console.log(`First character: ${first2}`) 
console.log(`Last character: ${last2}`)
